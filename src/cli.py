"""Run the Jev control loop against an existing Omarchy Fleet desktop."""

from time import perf_counter_ns, time_ns

_MODULE_START_NS = perf_counter_ns()
_MODULE_WALL_NS = time_ns()

import argparse
import asyncio
import json
import logging
import os
from pathlib import Path
import sys
import tomllib
from urllib.parse import urlsplit

from dotenv import load_dotenv
import httpx2
from typesafe_sdk import RetryPolicy, TypeSafeClient, TypeSafeError

if __package__:
    from .driver import CuaDriver, DriverError, PINNED_DRIVER_VERSION
    from .pipeline import DEFAULT_MAX_ITERATIONS, run_pipeline
    from .reporting import RunReport
    from .selection import ChoiceSelector, PINNED_MODEL, SelectionError
else:
    from driver import CuaDriver, DriverError, PINNED_DRIVER_VERSION
    from pipeline import DEFAULT_MAX_ITERATIONS, run_pipeline
    from reporting import RunReport
    from selection import ChoiceSelector, PINNED_MODEL, SelectionError

_IMPORT_FINISHED_NS = perf_counter_ns()


async def _run(args, request, text, config, api_key, report):
    driver = CuaDriver(claim_file=args.claim_file)
    result = None
    try:
        with report.span("driver_initialization"):
            await driver.start(url=args.url)
        expected = config["cua-driver-version"]
        if driver.server_info.get("version") != expected:
            raise DriverError(f"This integration requires Cua Driver {expected}.", code="driver_version_mismatch")
        report.append("driver_connected", **driver.session_info)
        print(f"Remote desktop: {driver.desktop_url}", file=sys.stderr)
        with report.span("initialization.http_client"):
            http_client = httpx2.Client(timeout=30.0, event_hooks={
                "request": [report.on_request], "response": [report.on_response],
            })
        with http_client:
            with TypeSafeClient(
                api_key=api_key, base_url="https://api.typesafe.ai", model=PINNED_MODEL,
                timeout=30.0, retry=RetryPolicy(max_retries=0), http_client=http_client,
            ) as client:
                selector = ChoiceSelector(client, model=PINNED_MODEL)
                with report.span("pipeline"):
                    result = await run_pipeline(
                        request, driver, selector, report=report,
                        max_iterations=args.max_iterations, text=text, screenshots=args.screenshots,
                    )
                return result
    finally:
        with report.span("driver_cleanup"):
            try:
                await driver.close()
                report.append("driver_disconnected", claim_retained=True, worker_shutdown_requested=False)
            except Exception as error:
                details = {"error_type": type(error).__name__}
                if isinstance(error, DriverError):
                    details.update(error.details())
                if result is not None:
                    result.observation["cleanup_error"] = details
                _report_failure(report, "driver_cleanup_error", **details)
                print("Driver session cleanup failed; the worker remains reserved. See the run report.", file=sys.stderr)


def main(argv=None, *, _include_imports=False):
    entered_ns = perf_counter_ns()
    project = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description="Let Jev select windows and controls, then execute through Cua Driver on an existing Omarchy Fleet desktop.")
    parser.add_argument("request", nargs="?", help="Original user request, retained in every Jev call")
    parser.add_argument("--request-file", type=Path, help="Read the exact request from a UTF-8 file")
    prepared = parser.add_mutually_exclusive_group()
    prepared.add_argument("--text", help="Exact text for one typing operation; never generated by Jev")
    prepared.add_argument("--text-file", type=Path, help="Read exact UTF-8 typing text")
    parser.add_argument("--url", help="Open this HTTP(S) URL through Driver in the remote default browser; omit to continue the desktop")
    parser.add_argument("--claim-file", type=Path, default=project / ".local/omarchy-fleet/claim.json", help="Existing Fleet SDK claim reference; never creates a worker")
    parser.add_argument("--env-file", type=Path, default=project / ".env", help="Local TypeSafe credentials")
    parser.add_argument("--fleet-env-file", type=Path, default=project / ".env.fleet", help="Local Fleet credentials")
    parser.add_argument("--max-iterations", type=int, default=DEFAULT_MAX_ITERATIONS, help="Observation/action bound, not a task-completion check")
    parser.add_argument("--screenshots", action=argparse.BooleanOptionalAction, default=True, help="Save desktop PNGs before/after actions; never sent to Jev")
    args = parser.parse_args(argv)
    if (args.request is None) == (args.request_file is None):
        parser.error("provide exactly one request argument or --request-file")
    if args.max_iterations < 1:
        parser.error("--max-iterations must be positive")
    if args.url is not None:
        try:
            url = urlsplit(args.url)
            valid = url.scheme.lower() in {"http", "https"} and bool(url.hostname) and not url.username and not url.password
            url.port
        except ValueError:
            valid = False
        if not valid:
            parser.error("--url must be an absolute HTTP(S) URL without embedded credentials")
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8")
    logging.basicConfig(level=logging.WARNING, stream=sys.stderr)
    logging.getLogger(ChoiceSelector.__module__).setLevel(logging.INFO)
    report, output, exit_code = None, None, 1
    try:
        report = RunReport(
            project / "reports", origin_ns=_MODULE_START_NS if _include_imports else entered_ns,
            origin_wall_ns=_MODULE_WALL_NS if _include_imports else time_ns(),
            origin_label="desktop_cli_module_after_time_import" if _include_imports else "main_call",
        )
        if _include_imports:
            report.record_interval("startup.imports", _MODULE_START_NS, _IMPORT_FINISHED_NS)
        report.record_interval("startup.cli", entered_ns, perf_counter_ns())
        print(f"Run report: {report.path}", file=sys.stderr)
        print(f"Jev input/output JSON: {report.requests_path}", file=sys.stderr)
        with report.span("initialization.request_read"):
            request = args.request_file.read_bytes().decode("utf-8") if args.request_file else args.request
            text = args.text_file.read_bytes().decode("utf-8") if args.text_file else args.text
        with report.span("initialization.configuration"):
            if not request.strip():
                raise ValueError("The original request must be nonempty.")
            config = tomllib.loads((project / "pyproject.toml").read_text(encoding="utf-8"))["tool"]["ctrlloop"]
            if config["jev-model"] != PINNED_MODEL:
                raise ValueError(f"pyproject.toml must retain {PINNED_MODEL}.")
            if config["cua-driver-version"] != PINNED_DRIVER_VERSION:
                raise ValueError(f"pyproject.toml must retain Cua Driver {PINNED_DRIVER_VERSION}.")
            load_dotenv(args.env_file, override=False, interpolate=False)
            load_dotenv(args.fleet_env_file, override=False, interpolate=False)
            api_key = os.environ.get("TYPESAFE_API_KEY", "").strip()
            if not api_key:
                raise ValueError("TYPESAFE_API_KEY is missing; set it in the environment or --env-file.")
        report.append("run_started", request=request, url=args.url, screenshots=args.screenshots,
                      backend="cua_driver", worker="existing_fleet_claim", **({"text": text} if text is not None else {}))
        result = asyncio.run(_run(args, request, text, config, api_key, report))
        output = result.to_dict()
        report.append("run_finished", result=output)
        exit_code = 1 if result.status in {"error", "observation_unavailable", "action_unconfirmed"} else 2
    except (DriverError, SelectionError, ValueError, OSError, TypeSafeError, KeyError) as error:
        message = str(error) if isinstance(error, (DriverError, SelectionError)) or type(error) is ValueError else f"Pipeline failed: {type(error).__name__}. Check local configuration and connectivity."
        output = {"status": "error", "error": message, **(error.details() if isinstance(error, DriverError) else {})}
        _report_failure(report, "run_error", **output)
    except (KeyboardInterrupt, SystemExit) as error:
        _report_failure(report, "run_interrupted", error_type=type(error).__name__)
        raise
    except Exception as error:
        output = {"status": "error", "error": f"Pipeline failed: {type(error).__name__}. Check local configuration and connectivity."}
        _report_failure(report, "run_error", **output)
    finally:
        if report is not None:
            try:
                timing = report.close()
                if output is not None:
                    output["timing"] = timing
            except (OSError, ValueError, RuntimeError):
                print("Could not save all run-report files.", file=sys.stderr)
                exit_code = 1
    print(json.dumps(output, ensure_ascii=False, indent=2))
    return exit_code


def _report_failure(report, event, **details):
    if report is not None:
        try:
            report.append(event, **details)
        except (OSError, ValueError):
            print("Could not buffer the final report entry.", file=sys.stderr)


if __name__ == "__main__":
    raise SystemExit(main(_include_imports=True))
